"""Exports: JSON, CSV (tensor table), GitHub-flavoured Markdown, and model comparison."""

from __future__ import annotations

import csv
import io
from typing import Any

from pydantic import BaseModel

from .memory import MemoryEstimate, MemoryRequest, estimate_memory, weight_estimates
from .schemas import ScanResult

_PROV_MARK = {"verified": "✔ verified", "derived": "= derived", "inferred": "~ inferred"}


def fmt_bytes(n: int | float | None) -> str:
    if n is None:
        return "—"
    n = float(n)
    for unit in ("B", "KiB", "MiB", "GiB", "TiB"):
        if abs(n) < 1024 or unit == "TiB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.2f} {unit}"
        n /= 1024
    return f"{n:.2f} TiB"


def fmt_count(n: int | None) -> str:
    if n is None:
        return "—"
    for div, suf in ((1e12, "T"), (1e9, "B"), (1e6, "M"), (1e3, "K")):
        if n >= div:
            return f"{n / div:.2f}{suf}"
    return str(n)


def _csv_cell(v: Any) -> str:
    """Neutralise spreadsheet formula injection from untrusted tensor names."""
    s = "" if v is None else str(v)
    return "'" + s if s[:1] in ("=", "+", "-", "@", "\t", "\r") else s


def tensors_csv(scan: ScanResult) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["name", "shape", "shape_order", "dtype", "n_elements", "n_bytes", "offset", "file", "stack", "layer", "component", "role"])
    for t in scan.tensors:
        w.writerow(
            [_csv_cell(x) for x in (
                t.name, "x".join(map(str, t.shape)), t.shape_order, t.dtype, t.n_elements, t.n_bytes, t.offset,
                scan.files[t.file_index].path if t.file_index < len(scan.files) else t.file_index,
                t.stack, t.layer, t.component, t.role,
            )]
        )
    return buf.getvalue()


def _md_escape(s: Any) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ").replace("<", "&lt;").replace(">", "&gt;")


def markdown_report(scan: ScanResult, mem: MemoryEstimate | None = None) -> str:
    mem = mem or estimate_memory(scan, MemoryRequest())
    L: list[str] = []
    L.append(f"# Model Surgery report: {_md_escape(scan.name)}")
    L.append("")
    L.append(f"_Generated by Model Surgery {scan.app_version} · scanned {scan.scanned_at}_")
    L.append("")
    L.append("| | |")
    L.append("|---|---|")
    L.append(f"| Source | `{_md_escape(scan.path)}` |")
    L.append(f"| Format | {_md_escape(scan.format.name)} {scan.format.version or ''} |")
    L.append(f"| Files | {len(scan.files)} ({fmt_bytes(scan.total_size_bytes)}) |")
    L.append(f"| Quantization | {_md_escape(scan.quantization.label or '—')} ({scan.quantization.label_provenance or 'unknown'}) |")
    if scan.quantization.effective_bits_per_weight:
        L.append(f"| Effective bits/weight | {scan.quantization.effective_bits_per_weight} (derived) |")
    L.append(f"| Tensors | {len(scan.tensors):,} |")
    L.append(f"| Integrity | {'✅ passed' if scan.integrity.valid else '❌ ' + str(len(scan.integrity.errors)) + ' error(s)'} |")
    L.append("")
    L.append("Provenance legend: **✔ verified** = read from the file · **= derived** = computed from verified values · **~ inferred** = heuristic.")
    L.append("")
    L.append("## Hyperparameters")
    L.append("")
    L.append("| Property | Value | Provenance | Source |")
    L.append("|---|---|---|---|")
    for f in scan.hyperparameters:
        v = f"{f.value:,}" if isinstance(f.value, int) and not isinstance(f.value, bool) else f.value
        L.append(f"| {_md_escape(f.label)} | {_md_escape(v)} | {_PROV_MARK[f.provenance]} | {_md_escape(f.source)} |")
    L.append("")
    L.append("## Tensor types")
    L.append("")
    L.append("| dtype | tensors | elements | bytes |")
    L.append("|---|---:|---:|---:|")
    for d in scan.dtype_breakdown:
        L.append(f"| {d.dtype} | {d.n_tensors:,} | {d.n_elements:,} | {fmt_bytes(d.n_bytes)} |")
    L.append("")
    L.append("## Architecture (inferred from tensor names)")
    L.append("")
    if scan.architecture.stacks:
        for s in scan.architecture.stacks:
            comps = sorted({c.component for l in s.layers for c in l.components})
            L.append(f"- `{_md_escape(s.prefix)}`: {s.n_layers} layers, {fmt_bytes(s.n_bytes)}, components: {', '.join(comps)}{' (primary)' if s.primary else ''}")
    for c in scan.architecture.globals:
        L.append(f"- {c.component}: {', '.join('`' + _md_escape(t) + '`' for t in c.tensors[:4])}{' …' if len(c.tensors) > 4 else ''} ({fmt_bytes(c.n_bytes)})")
    for n in scan.architecture.notes:
        L.append(f"- _note:_ {_md_escape(n)}")
    L.append("")
    L.append("## Weight storage estimates")
    L.append("")
    L.append("> Estimates, not measurements.")
    L.append("")
    L.append("| Format | Size | Bits/weight | Provenance |")
    L.append("|---|---:|---:|---|")
    for w in mem.weights:
        L.append(f"| {_md_escape(w.label)} | {fmt_bytes(w.bytes)} | {w.bits_per_weight} | {_PROV_MARK[w.provenance]} |")
    L.append("")
    L.append(f"## Inference memory estimate ({_md_escape(mem.selected_weights.label)})")
    L.append("")
    L.append("| Component | Size | Provenance | Formula |")
    L.append("|---|---:|---|---|")
    for c in mem.inference:
        L.append(f"| {_md_escape(c.label)} | {fmt_bytes(c.bytes)} | {_PROV_MARK[c.provenance]} | {_md_escape(c.formula)} |")
    L.append(f"| **Total** | **{fmt_bytes(mem.total_bytes)}** | | |")
    L.append("")
    for a in mem.assumptions:
        L.append(f"- {_md_escape(a)}")
    if mem.fit:
        fit = mem.fit
        L.append("")
        L.append(f"**{_md_escape(fit.device_name)}:** {fit.verdict.replace('_', ' ')} — needs ~{fmt_bytes(fit.required_bytes)} of ~{fmt_bytes(fit.usable_bytes)} usable (estimate).")
    if scan.integrity.errors or scan.integrity.warnings:
        L.append("")
        L.append("## Integrity findings")
        L.append("")
        for e in scan.integrity.errors[:50]:
            L.append(f"- ❌ {_md_escape(e)}")
        for w in scan.integrity.warnings[:50]:
            L.append(f"- ⚠️ {_md_escape(w)}")
    L.append("")
    return "\n".join(L)


class CompareRow(BaseModel):
    section: str
    label: str
    a: str
    b: str
    differs: bool


class Comparison(BaseModel):
    a_id: str
    b_id: str
    a_name: str
    b_name: str
    rows: list[CompareRow]
    tensors_only_in_a: int
    tensors_only_in_b: int
    tensors_shape_changed: int
    tensors_dtype_changed: int
    dtype_changes: list[dict]
    note: str


def compare(a: ScanResult, b: ScanResult, req: MemoryRequest | None = None) -> Comparison:
    req = req or MemoryRequest()
    ma, mb = estimate_memory(a, req), estimate_memory(b, req)
    rows: list[CompareRow] = []

    def show(v: Any) -> str:
        if v is None:
            return "—"
        return f"{v:,}" if isinstance(v, int) and not isinstance(v, bool) else str(v)

    def add(section: str, label: str, va: Any, vb: Any) -> None:
        sa, sb = show(va), show(vb)
        rows.append(CompareRow(section=section, label=label, a=sa, b=sb, differs=sa != sb))

    add("Source", "Format", f"{a.format.name} {a.format.version or ''}".strip(), f"{b.format.name} {b.format.version or ''}".strip())
    add("Source", "Files on disk", fmt_bytes(a.total_size_bytes), fmt_bytes(b.total_size_bytes))
    add("Source", "Integrity", "valid" if a.integrity.valid else "errors", "valid" if b.integrity.valid else "errors")
    keys = []
    for f in a.hyperparameters + b.hyperparameters:
        if f.key not in keys:
            keys.append(f.key)
    for k in keys:
        fa, fb = a.fact(k), b.fact(k)
        label = (fa or fb).label  # type: ignore[union-attr]
        add("Architecture", label, fa.value if fa else None, fb.value if fb else None)
    add("Architecture", "Primary layer stack", _stack_desc(a), _stack_desc(b))
    add("Quantization", "Label", a.quantization.label, b.quantization.label)
    add("Quantization", "Effective bits/weight", a.quantization.effective_bits_per_weight, b.quantization.effective_bits_per_weight)
    add("Quantization", "Tensor types", _dtype_desc(a), _dtype_desc(b))
    wa = {w.id: w for w in weight_estimates(a)}
    wb = {w.id: w for w in weight_estimates(b)}
    for wid in ["current", "fp16", "q8_0", "q4_k_m"]:
        if wid in wa or wid in wb:
            label = (wa.get(wid) or wb.get(wid)).label if wid != "current" else "As stored"  # type: ignore[union-attr]
            add("Weights (estimate)", label, fmt_bytes(wa[wid].bytes) if wid in wa else None, fmt_bytes(wb[wid].bytes) if wid in wb else None)
    for ca in ma.inference:
        cb = next((c for c in mb.inference if c.key == ca.key), None)
        add(f"Inference @ {req.context_length:,} ctx (estimate)", ca.label.split(" (")[0], fmt_bytes(ca.bytes), fmt_bytes(cb.bytes) if cb else None)
    add(f"Inference @ {req.context_length:,} ctx (estimate)", "Total", fmt_bytes(ma.total_bytes), fmt_bytes(mb.total_bytes))
    if ma.fit and mb.fit:
        add("Device fit (estimate)", ma.fit.device_name, ma.fit.verdict.replace("_", " "), mb.fit.verdict.replace("_", " "))

    ta = {t.name: t for t in a.tensors}
    tb = {t.name: t for t in b.tensors}
    common = ta.keys() & tb.keys()
    changes: dict[tuple[str, str], int] = {}
    shape_changed = 0
    for n in common:
        if ta[n].n_elements != tb[n].n_elements:
            shape_changed += 1
        if ta[n].dtype != tb[n].dtype:
            changes[(ta[n].dtype, tb[n].dtype)] = changes.get((ta[n].dtype, tb[n].dtype), 0) + 1
    note = ""
    if a.kind != b.kind:
        note = "models use different formats; tensor names follow different conventions so per-tensor comparison is limited"
    return Comparison(
        a_id=a.id,
        b_id=b.id,
        a_name=_display_name(a),
        b_name=_display_name(b),
        rows=rows,
        tensors_only_in_a=len(ta.keys() - tb.keys()),
        tensors_only_in_b=len(tb.keys() - ta.keys()),
        tensors_shape_changed=shape_changed,
        tensors_dtype_changed=sum(changes.values()),
        dtype_changes=[{"from": k[0], "to": k[1], "count": v} for k, v in sorted(changes.items(), key=lambda x: -x[1])],
        note=note,
    )


def _display_name(s: ScanResult) -> str:
    # Quantized variants usually share general.name, so include the label to tell them apart.
    return f"{s.name} ({s.quantization.label})" if s.quantization.label else s.name


def _stack_desc(s: ScanResult) -> str | None:
    p = next((x for x in s.architecture.stacks if x.primary), None)
    return f"{p.prefix} × {p.n_layers}" if p else None


def _dtype_desc(s: ScanResult) -> str:
    return ", ".join(f"{d.dtype}:{d.n_tensors}" for d in s.dtype_breakdown)


def comparison_markdown(c: Comparison) -> str:
    L = [f"# Model comparison", "", f"**A:** {_md_escape(c.a_name)}  ", f"**B:** {_md_escape(c.b_name)}", ""]
    section = None
    for r in c.rows:
        if r.section != section:
            section = r.section
            L += ["", f"### {_md_escape(section)}", "", "| | A | B |", "|---|---|---|"]
        mark = " **≠**" if r.differs else ""
        L.append(f"| {_md_escape(r.label)}{mark} | {_md_escape(r.a)} | {_md_escape(r.b)} |")
    L += [
        "",
        "### Tensors",
        "",
        f"- only in A: {c.tensors_only_in_a}, only in B: {c.tensors_only_in_b}",
        f"- element count changed: {c.tensors_shape_changed}",
        f"- dtype changed: {c.tensors_dtype_changed}",
    ]
    for d in c.dtype_changes[:20]:
        L.append(f"  - {d['from']} → {d['to']}: {d['count']}")
    if c.note:
        L += ["", f"_{_md_escape(c.note)}_"]
    L += ["", "_Size and memory figures are estimates unless labelled 'As stored'._", ""]
    return "\n".join(L)
