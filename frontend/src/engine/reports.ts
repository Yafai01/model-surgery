import type { Comparison, CompareRow, MemoryEstimate, MemoryRequest, ScanResult } from "../types";
import { estimateMemory, weightEstimates } from "./memory";

const PROV_MARK = { verified: "✔ verified", derived: "= derived", inferred: "~ inferred" } as const;

export const DEFAULT_MEMORY_REQUEST: MemoryRequest = {
  weight_format: "current", context_length: 4096, batch_size: 1, kv_cache_type: "f16", flash_attention: true, n_ubatch: 512,
  device_id: "laptop-cpu-16gb", custom_device: null,
};

export function fmtBytesPy(n: number | null | undefined): string {
  if (n === null || n === undefined) return "—";
  let v = n;
  for (const unit of ["B", "KiB", "MiB", "GiB", "TiB"]) {
    if (Math.abs(v) < 1024 || unit === "TiB") return unit === "B" ? `${v.toFixed(0)} B` : `${v.toFixed(2)} ${unit}`;
    v /= 1024;
  }
  return `${v.toFixed(2)} TiB`;
}

const csvCell = (v: unknown) => {
  const s = v === null || v === undefined ? "" : String(v);
  const safe = /^[=+\-@\t\r]/.test(s) ? "'" + s : s;
  return /[",\n\r]/.test(safe) ? `"${safe.replace(/"/g, '""')}"` : safe;
};

export function tensorsCsv(scan: ScanResult): string {
  const rows = [["name", "shape", "shape_order", "dtype", "n_elements", "n_bytes", "offset", "file", "stack", "layer", "component", "role"].join(",")];
  for (const t of scan.tensors) {
    rows.push(
      [t.name, t.shape.join("x"), t.shape_order, t.dtype, t.n_elements, t.n_bytes, t.offset, scan.files[t.file_index]?.path ?? t.file_index, t.stack, t.layer, t.component, t.role]
        .map(csvCell)
        .join(","),
    );
  }
  return rows.join("\n") + "\n";
}

const md = (s: unknown) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ").replace(/</g, "&lt;").replace(/>/g, "&gt;");
/** Python repr() for non-integer floats: exponent form below 1e-4 or from 1e16, two-digit exponent. */
function pyFloat(v: number): string {
  if (!Number.isFinite(v) || v === 0) return String(v);
  const exp = Math.floor(Math.log10(Math.abs(v)));
  if (exp < -4 || exp >= 16) return v.toExponential().replace(/e([+-])(\d)$/, "e$10$2");
  return String(v);
}
const fmtVal = (v: unknown) =>
  typeof v === "number" ? (Number.isInteger(v) ? v.toLocaleString("en-US") : pyFloat(v)) : v === true ? "True" : v === false ? "False" : String(v);

export function markdownReport(scan: ScanResult, mem?: MemoryEstimate): string {
  const m = mem ?? estimateMemory(scan, DEFAULT_MEMORY_REQUEST);
  const L: string[] = [];
  L.push(`# Model Surgery report: ${md(scan.name)}`, "", `_Generated by Model Surgery ${scan.app_version} · scanned ${scan.scanned_at}_`, "", "| | |", "|---|---|");
  L.push(`| Source | \`${md(scan.path)}\` |`);
  L.push(`| Format | ${md(scan.format.name)} ${scan.format.version ?? ""} |`);
  L.push(`| Files | ${scan.files.length} (${fmtBytesPy(scan.total_size_bytes)}) |`);
  L.push(`| Quantization | ${md(scan.quantization.label ?? "—")} (${scan.quantization.label_provenance ?? "unknown"}) |`);
  if (scan.quantization.effective_bits_per_weight) L.push(`| Effective bits/weight | ${scan.quantization.effective_bits_per_weight} (derived) |`);
  L.push(`| Tensors | ${scan.tensors.length.toLocaleString("en-US")} |`);
  L.push(`| Integrity | ${scan.integrity.valid ? "✅ passed" : `❌ ${scan.integrity.errors.length} error(s)`} |`, "");
  L.push("Provenance legend: **✔ verified** = read from the file · **= derived** = computed from verified values · **~ inferred** = heuristic.", "");
  L.push("## Hyperparameters", "", "| Property | Value | Provenance | Source |", "|---|---|---|---|");
  for (const f of scan.hyperparameters) L.push(`| ${md(f.label)} | ${md(fmtVal(f.value))} | ${PROV_MARK[f.provenance]} | ${md(f.source)} |`);
  L.push("", "## Tensor types", "", "| dtype | tensors | elements | bytes |", "|---|---:|---:|---:|");
  for (const d of scan.dtype_breakdown) L.push(`| ${d.dtype} | ${d.n_tensors.toLocaleString("en-US")} | ${d.n_elements.toLocaleString("en-US")} | ${fmtBytesPy(d.n_bytes)} |`);
  L.push("", "## Architecture (inferred from tensor names)", "");
  for (const s of scan.architecture.stacks) {
    const comps = [...new Set(s.layers.flatMap((l) => l.components.map((c) => c.component)))].sort();
    L.push(`- \`${md(s.prefix)}\`: ${s.n_layers} layers, ${fmtBytesPy(s.n_bytes)}, components: ${comps.join(", ")}${s.primary ? " (primary)" : ""}`);
  }
  for (const c of scan.architecture.globals)
    L.push(`- ${c.component}: ${c.tensors.slice(0, 4).map((t) => "`" + md(t) + "`").join(", ")}${c.tensors.length > 4 ? " …" : ""} (${fmtBytesPy(c.n_bytes)})`);
  for (const n of scan.architecture.notes) L.push(`- _note:_ ${md(n)}`);
  L.push("", "## Weight storage estimates", "", "> Estimates, not measurements.", "", "| Format | Size | Bits/weight | Provenance |", "|---|---:|---:|---|");
  for (const w of m.weights) L.push(`| ${md(w.label)} | ${fmtBytesPy(w.bytes)} | ${w.bits_per_weight} | ${PROV_MARK[w.provenance]} |`);
  L.push("", `## Inference memory estimate (${md(m.selected_weights.label)})`, "", "| Component | Size | Provenance | Formula |", "|---|---:|---|---|");
  for (const c of m.inference) L.push(`| ${md(c.label)} | ${fmtBytesPy(c.bytes)} | ${PROV_MARK[c.provenance]} | ${md(c.formula)} |`);
  L.push(`| **Total** | **${fmtBytesPy(m.total_bytes)}** | | |`, "");
  for (const a of m.assumptions) L.push(`- ${md(a)}`);
  if (m.fit) L.push("", `**${md(m.fit.device_name)}:** ${m.fit.verdict.replace(/_/g, " ")} — needs ~${fmtBytesPy(m.fit.required_bytes)} of ~${fmtBytesPy(m.fit.usable_bytes)} usable (estimate).`);
  if (scan.integrity.errors.length || scan.integrity.warnings.length) {
    L.push("", "## Integrity findings", "");
    for (const e of scan.integrity.errors.slice(0, 50)) L.push(`- ❌ ${md(e)}`);
    for (const w of scan.integrity.warnings.slice(0, 50)) L.push(`- ⚠️ ${md(w)}`);
  }
  L.push("");
  return L.join("\n");
}

const displayName = (s: ScanResult) => (s.quantization.label ? `${s.name} (${s.quantization.label})` : s.name);
const stackDesc = (s: ScanResult) => {
  const p = s.architecture.stacks.find((x) => x.primary);
  return p ? `${p.prefix} × ${p.n_layers}` : null;
};
const dtypeDesc = (s: ScanResult) => s.dtype_breakdown.map((d) => `${d.dtype}:${d.n_tensors}`).join(", ");

export function compare(a: ScanResult, b: ScanResult, req: MemoryRequest = DEFAULT_MEMORY_REQUEST): Comparison {
  const ma = estimateMemory(a, req);
  const mb = estimateMemory(b, req);
  const rows: CompareRow[] = [];
  const show = (v: unknown) => (v === null || v === undefined ? "—" : typeof v === "number" && Number.isInteger(v) ? v.toLocaleString("en-US") : fmtVal(v));
  const add = (section: string, label: string, va: unknown, vb: unknown) => {
    const [sa, sb] = [show(va), show(vb)];
    rows.push({ section, label, a: sa, b: sb, differs: sa !== sb });
  };
  add("Source", "Format", `${a.format.name} ${a.format.version ?? ""}`.trim(), `${b.format.name} ${b.format.version ?? ""}`.trim());
  add("Source", "Files on disk", fmtBytesPy(a.total_size_bytes), fmtBytesPy(b.total_size_bytes));
  add("Source", "Integrity", a.integrity.valid ? "valid" : "errors", b.integrity.valid ? "valid" : "errors");
  const keys: string[] = [];
  for (const f of [...a.hyperparameters, ...b.hyperparameters]) if (!keys.includes(f.key)) keys.push(f.key);
  for (const k of keys) {
    const fa = a.hyperparameters.find((f) => f.key === k);
    const fb = b.hyperparameters.find((f) => f.key === k);
    add("Architecture", (fa ?? fb)!.label, fa?.value ?? null, fb?.value ?? null);
  }
  add("Architecture", "Primary layer stack", stackDesc(a), stackDesc(b));
  add("Quantization", "Label", a.quantization.label, b.quantization.label);
  add("Quantization", "Effective bits/weight", a.quantization.effective_bits_per_weight, b.quantization.effective_bits_per_weight);
  add("Quantization", "Tensor types", dtypeDesc(a), dtypeDesc(b));
  const wa = new Map(weightEstimates(a).map((w) => [w.id, w]));
  const wb = new Map(weightEstimates(b).map((w) => [w.id, w]));
  for (const id of ["current", "fp16", "q8_0", "q4_k_m"]) {
    if (wa.has(id) || wb.has(id)) {
      const label = id === "current" ? "As stored" : (wa.get(id) ?? wb.get(id))!.label;
      add("Weights (estimate)", label, wa.has(id) ? fmtBytesPy(wa.get(id)!.bytes) : null, wb.has(id) ? fmtBytesPy(wb.get(id)!.bytes) : null);
    }
  }
  const sec = `Inference @ ${req.context_length.toLocaleString("en-US")} ctx (estimate)`;
  for (const ca of ma.inference) {
    const cb = mb.inference.find((c) => c.key === ca.key);
    add(sec, ca.label.split(" (")[0], fmtBytesPy(ca.bytes), cb ? fmtBytesPy(cb.bytes) : null);
  }
  add(sec, "Total", fmtBytesPy(ma.total_bytes), fmtBytesPy(mb.total_bytes));
  if (ma.fit && mb.fit) add("Device fit (estimate)", ma.fit.device_name, ma.fit.verdict.replace(/_/g, " "), mb.fit.verdict.replace(/_/g, " "));

  const ta = new Map(a.tensors.map((t) => [t.name, t]));
  const tb = new Map(b.tensors.map((t) => [t.name, t]));
  const changes = new Map<string, number>();
  let shapeChanged = 0;
  for (const [n, x] of ta) {
    const y = tb.get(n);
    if (!y) continue;
    if (x.n_elements !== y.n_elements) shapeChanged++;
    if (x.dtype !== y.dtype) changes.set(`${x.dtype}\u0000${y.dtype}`, (changes.get(`${x.dtype}\u0000${y.dtype}`) ?? 0) + 1);
  }
  return {
    a_id: a.id, b_id: b.id, a_name: displayName(a), b_name: displayName(b), rows,
    tensors_only_in_a: [...ta.keys()].filter((k) => !tb.has(k)).length,
    tensors_only_in_b: [...tb.keys()].filter((k) => !ta.has(k)).length,
    tensors_shape_changed: shapeChanged,
    tensors_dtype_changed: [...changes.values()].reduce((x, y) => x + y, 0),
    dtype_changes: [...changes.entries()].sort((p, q) => q[1] - p[1]).map(([k, count]) => ({ from: k.split("\u0000")[0], to: k.split("\u0000")[1], count })),
    note: a.kind !== b.kind ? "models use different formats; tensor names follow different conventions so per-tensor comparison is limited" : "",
  };
}

export function comparisonMarkdown(c: Comparison): string {
  const L = ["# Model comparison", "", `**A:** ${md(c.a_name)}  `, `**B:** ${md(c.b_name)}`, ""];
  let section: string | null = null;
  for (const r of c.rows) {
    if (r.section !== section) {
      section = r.section;
      L.push("", `### ${md(section)}`, "", "| | A | B |", "|---|---|---|");
    }
    L.push(`| ${md(r.label)}${r.differs ? " **≠**" : ""} | ${md(r.a)} | ${md(r.b)} |`);
  }
  L.push("", "### Tensors", "", `- only in A: ${c.tensors_only_in_a}, only in B: ${c.tensors_only_in_b}`, `- element count changed: ${c.tensors_shape_changed}`, `- dtype changed: ${c.tensors_dtype_changed}`);
  for (const d of c.dtype_changes.slice(0, 20)) L.push(`  - ${d.from} → ${d.to}: ${d.count}`);
  if (c.note) L.push("", `_${md(c.note)}_`);
  L.push("", "_Size and memory figures are estimates unless labelled 'As stored'._", "");
  return L.join("\n");
}
